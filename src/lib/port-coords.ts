export function getPortCoords(location: string): [number, number] | null {
  // Direct match
  if (PORT_COORDS[location]) return PORT_COORDS[location];
  // Case-insensitive match
  const lower = location.toLowerCase();
  for (const [key, coords] of Object.entries(PORT_COORDS)) {
    if (key.toLowerCase() === lower) return coords;
  }
  // Partial match (location contains key or key contains location)
  for (const [key, coords] of Object.entries(PORT_COORDS)) {
    if (lower.includes(key.toLowerCase()) || key.toLowerCase().includes(lower)) return coords;
  }
  return null;
}
